"""Measured |C|-axis stress test: CCAR-E/H vs NICP on synthetic wide tables.

Generates controlled tables with fixed |U| and increasing |C|, runs reducers
once on the full table (no CV; wall-clock comparison), and writes CSV + LaTeX
snippet for Section sec:exp:boundary.
"""

from __future__ import annotations

import argparse
import csv
import time
from pathlib import Path

import numpy as np

from baselines.nicp import nicp_reduction
from baselines.wang_knn_nrs import wang_knn_nrs_reduction
from ccar.ccar_exact import ccar_nrs_exact
from ccar.ccar_heuristic import ccar_nrs_heuristic
from ccar.core import compute_core
from ccar.nrs import dependency_degree, normalize_features


ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "results_v7"
TEX_OUT = OUT_DIR / "wide_table_stress.tex"


def make_table(n: int, p: int, n_informative: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    # Informative block + noise block; labels from a linear rule on informative attrs.
    n_inf = min(n_informative, p)
    X_inf = rng.normal(size=(n, n_inf))
    coef = rng.normal(size=n_inf)
    logits = X_inf @ coef
    y = (logits > np.median(logits)).astype(int)
    if p > n_inf:
        X_noise = rng.normal(size=(n, p - n_inf))
        X = np.hstack([X_inf, X_noise])
    else:
        X = X_inf
    return X.astype(float), y


def run_one(X: np.ndarray, y: np.ndarray, delta: float, algo: str) -> dict:
    t0 = time.perf_counter()
    if algo == "ccar_e":
        res = ccar_nrs_exact(X, y, delta)
        R = res.reduct_indices
        n_core = len(res.core_indices)
        used_surr = bool(res.used_surrogate)
    elif algo == "ccar_h":
        res = ccar_nrs_heuristic(X, y, delta)
        R = res.reduct_indices
        n_core = len(res.core_indices)
        used_surr = bool(res.used_surrogate)
    elif algo == "nicp":
        R = nicp_reduction(X, y, delta)
        used_surr = False
    elif algo == "wang_knn":
        R = wang_knn_nrs_reduction(X, y, delta, k=3)
        used_surr = False
    else:
        raise ValueError(algo)
    elapsed = time.perf_counter() - t0
    # Core metadata for baselines is computed OUTSIDE the timer (prior to
    # 2026-09 it was inside, charging baselines for an n^2*|C| step they do
    # not perform; see review_opus_peerj_round2.md, row 16).
    if algo in ("nicp", "wang_knn"):
        core, _ = compute_core(normalize_features(X), y, delta)
        n_core = len(core)
    Xn = normalize_features(X)
    gC = dependency_degree(Xn, y, np.arange(Xn.shape[1]), delta)
    gR = dependency_degree(Xn, y, np.array(R, dtype=int), delta) if R else 0.0
    # For Wang, validity under delta-gamma is a cross-criterion check; still report.
    return {
        "runtime": elapsed,
        "n_reduct": len(R),
        "n_core": n_core,
        "used_surrogate": used_surr,
        "gamma_c": gC,
        "gamma_r": gR,
        "valid_delta": bool(R) and gR >= gC - 1e-9,
    }


def algos_for_p(p: int, exact_max_p: int) -> list[str]:
    """Skip Exact on wide tables: empty-core + large residual makes B&B impractical."""
    algos = ["ccar_h", "nicp", "wang_knn"]
    if p <= exact_max_p:
        algos = ["ccar_e"] + algos
    return algos


def write_tex(rows: list[dict], n: int, delta: float, path: Path) -> None:
    # Pivot for |C| rows — ratios vs CCAR-H (Exact omitted for large |C|).
    ps = sorted({r["p"] for r in rows})
    lines = [
        "% Auto-generated by experiments/run_wide_table_stress.py — do not edit by hand.",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Measured $|\\C|$-axis stress test on synthetic tables "
        f"($|\\U|={n}$, $\\delta={delta}$, single full-table run, seed per $|\\C|$). "
        "Times in seconds. Ratio ${>}1$ favours CCAR-H. "
        "CCAR-E is reported only for $|\\C|\\le 40$ (Exact hitting set is impractical on "
        "empty-core wide residuals). Values are observed, not extrapolated from "
        "Table~\\ref{tab:cost-crossover}. Wang: protocol-matched $k$NN-NRS greedy ($k{=}3$).}",
        "  \\label{tab:wide-table-stress}",
        "  \\footnotesize",
        "  \\setlength{\\tabcolsep}{3.5pt}",
        "  \\begin{tabular}{@{}rrrrrrrr@{}}",
        "    \\toprule",
        "    $|\\C|$ & $|\\CORE|$ & $t_{\\mathrm{E}}$ & $t_{\\mathrm{H}}$ & $t_{\\mathrm{NICP}}$ "
        "& $t_{\\mathrm{Wang}}$ & $t_{\\mathrm{NICP}}/t_{\\mathrm{H}}$ & $t_{\\mathrm{Wang}}/t_{\\mathrm{H}}$ \\\\",
        "    \\midrule",
    ]
    for p in ps:
        by = {r["algorithm"]: r for r in rows if r["p"] == p}
        h, ncp, w = by["ccar_h"], by["nicp"], by["wang_knn"]
        e = by.get("ccar_e")
        core_disp = 0 if h["used_surrogate"] else h["n_core"]
        e_str = f"{e['runtime']:.2f}" if e is not None else "---"
        ratio_n = ncp["runtime"] / h["runtime"] if h["runtime"] > 0 else float("nan")
        ratio_w = w["runtime"] / h["runtime"] if h["runtime"] > 0 else float("nan")
        lines.append(
            f"    {p} & {core_disp} & {e_str} & {h['runtime']:.2f} & "
            f"{ncp['runtime']:.2f} & {w['runtime']:.2f} & {ratio_n:.2f} & {ratio_w:.2f} \\\\"
        )
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}",
        "",
    ]
    path.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=400)
    ap.add_argument("--delta", type=float, default=0.1)
    ap.add_argument(
        "--p-list",
        type=str,
        default="20,40,60,80,100,150,200",
        help="Comma-separated |C| values",
    )
    ap.add_argument("--n-informative", type=int, default=10)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument(
        "--exact-max-p",
        type=int,
        default=40,
        help="Run CCAR-Exact only for |C| <= this (default 40).",
    )
    args = ap.parse_args()
    p_list = [int(x) for x in args.p_list.split(",") if x.strip()]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out_csv = OUT_DIR / "wide_table_stress_v7.csv"
    rows: list[dict] = []

    for p in p_list:
        X, y = make_table(args.n, p, args.n_informative, seed=args.seed + p)
        print(f"[wide] |U|={args.n} |C|={p} ...", flush=True)
        for algo in algos_for_p(p, args.exact_max_p):
            m = run_one(X, y, args.delta, algo)
            rec = {
                "n": args.n,
                "p": p,
                "n_informative": args.n_informative,
                "delta": args.delta,
                "seed": args.seed + p,
                "algorithm": algo,
                **m,
            }
            rows.append(rec)
            print(
                f"  {algo:10s} t={m['runtime']:.3f}s |R|={m['n_reduct']} "
                f"core={m['n_core']} surr={m['used_surrogate']} validΔ={m['valid_delta']}",
                flush=True,
            )

    with out_csv.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    write_tex(rows, args.n, args.delta, TEX_OUT)
    print(f"Wrote {out_csv}")
    print(f"Wrote {TEX_OUT}")


if __name__ == "__main__":
    main()
